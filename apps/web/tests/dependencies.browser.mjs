import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { projectSchema, catalogSchema } from '@andrea/contracts'
import { createApp } from '../../api/src/app.ts'
import { MemoryAccountStore, createJwt } from '../../api/src/auth.ts'

const release = (id, dependencies = []) => ({ id,version:'1.0.0',type:'release',loaders:['fabric'],gameVersions:['1.20.1'],dependencies,files:[{id:`${id}-file`,name:`${id}.jar`,primary:true,sources:[{id:'main',kind:'custom_http',url:'https://example.com/mod.jar'}]}] })
const make = (id,dependencies=[]) => projectSchema.parse({id,slug:id,title:id,description:id,type:'mod',loaders:['fabric'],gameVersions:['1.20.1'],versions:[release(id,dependencies)]})
const store = new MemoryAccountStore()
await store.createAccount({id:'qa',email:'qa@example.com',passwordHash:'',role:'root',createdAt:new Date().toISOString(),verifiedAt:null})
await store.saveStoredProject(make('test-mod',[{projectId:'test-library',dependencyType:'required'}]))
await store.saveStoredProject(make('test-library'))
const token = await createJwt({sub:'qa',email:'qa@example.com',role:'root'})
const app = createApp({authStore:store, externalFetch: async url => {
  const u = new URL(String(url))
  assert.equal(u.hostname, 'api.modrinth.com')
  if (u.pathname.endsWith('/version')) return Response.json([{ id:'remote-v1', project_id:'remote-id', version_number:'1.0.0', version_type:'release', status:'listed', game_versions:['1.20.1'], loaders:['fabric'], date_published:'2026-01-01T00:00:00.000Z', dependencies:[], files:[{filename:'external.jar',url:'https://cdn.modrinth.com/data/remote-id/external.jar',primary:true,size:100,hashes:{sha1:'a'.repeat(40)}}] }])
  return Response.json({id:'remote-id',slug:'remote-slug',title:'External MR Library',description:'',client_side:'optional',server_side:'optional'})
} })
const env = {CATALOG_JSON:JSON.stringify(catalogSchema.parse({schemaVersion:1,catalogRevision:'test',generatedAt:new Date().toISOString(),projects:[]}))}
const browser = await chromium.launch({executablePath:process.env.CHROME_PATH})
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}})
  await page.addInitScript(() => localStorage.setItem('andrea-editor-mode','textarea'))
  const errors = []; page.on('pageerror',e => errors.push(e.message))
  await page.route('**/api/**',async route => {
    const r = route.request(); const url = new URL(r.url()); const response = await app.request(url.pathname+url.search,{method:r.method(),headers:{...r.headers(),Authorization:`Bearer ${token}`},...(r.method() !== 'GET' ? {body:r.postData() || undefined} : {})},env)
    await route.fulfill({status:response.status,headers:{'Content-Type':'application/json'},body:await response.text()})
  })
  await page.goto(process.env.WEB_URL || 'http://127.0.0.1:9016/projects/test-mod')
  await page.getByText('依赖与安装清单',{exact:true}).first().click()
  await page.getByRole('button',{name:'解析依赖',exact:true}).click()
  await page.getByRole('button',{name:'导出安装清单'}).waitFor()
  assert.equal(await page.getByRole('button',{name:'导出安装清单'}).isEnabled(),true)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button',{name:'导出安装清单'}).click()
  assert.match((await downloadPromise).suggestedFilename(),/dependencies.json$/)
  await page.goto('http://127.0.0.1:9016/admin/projects/test-mod/edit')
  await page.getByRole('tab',{name:'版本与文件'}).click()
  await page.getByRole('button',{name:'添加依赖',exact:true}).click()
  assert.equal(await page.getByLabel('用途 / 联动功能说明').count(),2)
  await page.getByRole('button',{name:'删除依赖'}).last().click()
  await page.getByLabel('用途 / 联动功能说明').fill('Browser persisted dependency')
  await page.getByRole('button',{name:'添加依赖',exact:true}).click()
  await page.getByLabel('依赖来源',{exact:true}).last().click()
  await page.getByRole('option',{name:'Modrinth',exact:true}).click()
  await page.getByLabel('MR 项目 ID 或 slug（查询后绑定）').fill('remote-slug')
  await page.getByRole('button',{name:'查询并绑定',exact:true}).click()
  await page.waitForFunction(() => [...document.querySelectorAll('input')].some(el => el.value === 'remote-id'))
  await page.getByLabel('外部精确版本 / 文件（可选）').click()
  await page.getByRole('option',{name:'1.0.0',exact:true}).click()
  await page.getByRole('button',{name:'解析依赖',exact:true}).click()
  await page.getByRole('link',{name:'External MR Library · 1.0.0'}).waitFor()
  assert.equal(await page.getByRole('button',{name:'导出安装清单'}).isEnabled(),true)
  await page.getByRole('button',{name:'保存修改',exact:true}).click()
  await page.waitForURL('**/projects/test-mod')
  assert.equal((await store.getStoredProject('test-mod')).versions[0].dependencies[0].reason,'Browser persisted dependency')
  assert.deepEqual((await store.getStoredProject('test-mod')).versions[0].dependencies[1].external,{provider:'modrinth',projectId:'remote-id',versionId:'remote-v1'})
  await page.setViewportSize({width:390,height:844})
  await page.getByText('依赖与安装清单',{exact:true}).first().click()
  await page.getByRole('button',{name:'解析依赖',exact:true}).click()
  await page.getByRole('button',{name:'导出安装清单'}).waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2),true)
  assert.deepEqual(errors,[])
  console.log('Dependency UI: resolution, MR binding, draft preview, export, persistence and mobile passed')
} finally { await browser.close() }
